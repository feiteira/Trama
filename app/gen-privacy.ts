// Writes PRIVACY.md from the single list of outbound flows (app/src/core/privacy/flows.ts).
// CI runs this with --check and fails when PRIVACY.md is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { FLOWS, NO_NETWORK } from '../src/core/privacy/flows';

const HEAD = {
  en: { title: 'What leaves this device', intro: 'Sala keeps your practice on your computer. This is the complete list of ways anything leaves it. Each one happens only when you choose it.', when: 'When', what: 'What', who: 'Who can read it' },
  pt: { title: 'O que sai deste dispositivo', intro: 'O Sala guarda a sua prática no seu computador. Esta é a lista completa das formas de alguma coisa sair dele. Cada uma só acontece quando a escolhe.', when: 'Quando', what: 'O quê', who: 'Quem pode ler' },
  es: { title: 'Qué sale de este dispositivo', intro: 'Sala guarda su consulta en su ordenador. Esta es la lista completa de las formas en que algo puede salir de él. Cada una ocurre solo cuando usted lo elige.', when: 'Cuándo', what: 'Qué', who: 'Quién puede leerlo' },
} as const;

const LANGS = [['en', 'English'], ['pt', 'Português (Portugal)'], ['es', 'Español (España)']] as const;

let md = '# Privacy · Privacidade · Privacidad\n\n<!-- Generated by `npm run gen:privacy` from app/src/core/privacy/flows.ts. Do not edit by hand. -->\n\n';
md += LANGS.map(([l, name]) => `[${name}](#${HEAD[l].title.toLowerCase().replace(/[^a-zà-ú0-9 ]/g, '').replace(/ /g, '-')})`).join(' · ') + '\n';
for (const [l] of LANGS) {
  const h = HEAD[l];
  md += `\n## ${h.title}\n\n${h.intro}\n\n${NO_NETWORK[l]}\n\n| | ${h.when} | ${h.what} | ${h.who} |\n|---|---|---|---|\n`;
  for (const f of FLOWS) {
    const t = f.text[l];
    md += `| **${t.title}** | ${t.when} | ${t.what} | ${t.who} |\n`;
  }
}

const out = resolve(import.meta.dirname, '../../PRIVACY.md');
if (process.argv.includes('--check')) {
  const current = (() => {
    try {
      return readFileSync(out, 'utf8');
    } catch {
      return '';
    }
  })();
  if (current !== md) {
    console.error('PRIVACY.md is out of date. Run: npm run gen:privacy');
    process.exit(1);
  }
  console.log('PRIVACY.md is up to date.');
} else {
  writeFileSync(out, md);
  console.log(`Wrote ${out}`);
}
